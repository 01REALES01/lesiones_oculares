#DEFINICIÓN DE LA FUNCIÓN DE PREPROCESAMIENTO DE BEN GRAHAM
#los parámetros óptimos son sigmaX=10.1, alpha=4.12, gamma=-4
#La función pide como parámetros la imagen a procesar y el sigmaX, regresa la imagen procesada
def load_ben_color(img, sigmaX=10.1 ):
    image = cv2.cvtColor(img, cv2.COLOR_BGR2RGB)
    image = cv2.resize(image, (224, 224) , interpolation=cv2.INTER_CUBIC)   #resize a 224x224
    image=cv2.addWeighted ( image, 4.12, cv2.GaussianBlur( image , (0,0) , sigmaX) ,-4 ,128)  #preprocesado ben graham
    return image

