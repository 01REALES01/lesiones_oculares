#RECORTE (CROPPING) DE BORDES NEGROS INNECESARIOS, DEJA LA IMAGEN CUADRADA Y CENTRADA EN LA ZONA DE INTERÉS
#función para extraer los parámetros el contorno cicular de la imagen
def crop_img(img):
    img_gray = cv2.cvtColor(img, cv2.COLOR_BGR2GRAY)  #a escala de grises
    (t,thres) = cv2.threshold(img_gray, 10, 255, cv2.THRESH_BINARY) #aplicamos threshold para quedarnos con la mascara
    mask = cv2.medianBlur(thres,5)  #filtramos

    #detectamos círculo con hough, de ahí extremos el radio
    circ=cv2.HoughCircles(mask, cv2.HOUGH_GRADIENT,3,40, param1=50,param2=30,minRadius=500,maxRadius=2000)
    c = circ[0][0]   #el mejor circulo
    rad = int(c[2])
    cx = int(c[0])
    cy = int(c[1])
    img_crop = img[max(0, cy - rad) : max(0, cy + rad), max(0,cx - rad): max(0,cx + rad)]

    return img_crop

